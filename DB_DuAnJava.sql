CREATE DATABASE DuAnJava
USE DuAnJava;

-- 1. NHAN_VIEN (bang cha cua TAI_KHOAN va HOA_DON)
CREATE TABLE NHAN_VIEN (
    MaNV INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    GioiTinh BIT NOT NULL,                 -- 1: Nam, 0: Nu (quy uoc minh hoa)
    NgaySinh DATE NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    DiaChi NVARCHAR(255) NOT NULL,
    TrangThai BIT NOT NULL DEFAULT 1
);

-- 2. TAI_KHOAN: moi nhan vien toi da mot tai khoan
CREATE TABLE TAI_KHOAN (
    MaTK INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    MatKhau VARCHAR(500) NOT NULL,
    VaiTro VARCHAR(20) NOT NULL,
    TrangThai BIT NOT NULL DEFAULT 1,
    MaNV INT NOT NULL UNIQUE,
    CONSTRAINT FK_TK_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT CK_TK_VaiTro CHECK (VaiTro IN ('NHAN_VIEN', 'QUAN_LY'))
);

-- 3. DANH_MUC
CREATE TABLE DANH_MUC (
    MaDM INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TenDM NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(255) NOT NULL,
    NgayTao DATE NOT NULL,
    TrangThai BIT NOT NULL DEFAULT 1
);

-- 4. SAN_PHAM: mot danh muc co nhieu san pham
CREATE TABLE SAN_PHAM (
    MaSP INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TenSP NVARCHAR(200) NOT NULL,
    MaDM INT NOT NULL,
    ThuongHieu NVARCHAR(100) NOT NULL,
    GiaBan DECIMAL(18,2) NOT NULL,
    HinhAnh VARCHAR(255) NOT NULL,
    TrangThai BIT NOT NULL DEFAULT 1,
    CONSTRAINT FK_SP_DM FOREIGN KEY (MaDM) REFERENCES DANH_MUC(MaDM),
    CONSTRAINT CK_SP_GiaBan CHECK (GiaBan >= 0)
);

-- 5. KICH_CO: danh sach size dung chung
CREATE TABLE KICH_CO (
    MaKichCo INT IDENTITY(1,1) PRIMARY KEY,
    KichCo INT NOT NULL UNIQUE CHECK (KichCo > 0),
    TrangThai BIT NOT NULL DEFAULT 1
);

-- 6. SAN_PHAM_KICH_CO: bien the giay va ton kho
CREATE TABLE SAN_PHAM_KICH_CO (
    MaSPKC INT IDENTITY(1,1) PRIMARY KEY,
    MaSP INT NOT NULL REFERENCES SAN_PHAM(MaSP),
    MaKichCo INT NOT NULL REFERENCES KICH_CO(MaKichCo),
    SoLuongTon INT NOT NULL DEFAULT 0 CHECK (SoLuongTon >= 0),
    NgayCapNhat DATETIME NOT NULL DEFAULT GETDATE(),
    TrangThai BIT NOT NULL DEFAULT 1,
    CONSTRAINT UQ_SPKC UNIQUE (MaSP, MaKichCo)
);

-- 7. HOA_DON: mot nhan vien lap duoc nhieu hoa don
CREATE TABLE HOA_DON (
    MaHD INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaNV INT NOT NULL,
    NgayLap DATETIME NOT NULL,
    TongTien DECIMAL(18,2) NOT NULL,
    TienKhachDua DECIMAL(18,2) NOT NULL,
    TienThua DECIMAL(18,2) NOT NULL,
    TrangThai BIT NOT NULL DEFAULT 1,
    CONSTRAINT FK_HD_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT CK_HD_TongTien CHECK (TongTien >= 0),
    CONSTRAINT CK_HD_TienKhachDua CHECK (TienKhachDua >= 0),
    CONSTRAINT CK_HD_TienThua CHECK (TienThua >= 0),
    CONSTRAINT CK_HD_ThanhToan CHECK (TrangThai = 0 OR (TienKhachDua >= TongTien AND TienThua = TienKhachDua - TongTien))
);

-- 8. CHI_TIET_HOA_DON: luu bien the giay da ban
CREATE TABLE CHI_TIET_HOA_DON (
    MaCTHD INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaHD INT NOT NULL,
    MaSPKC INT NOT NULL,
    SoLuong INT NOT NULL,
    DonGia DECIMAL(18,2) NOT NULL,
    ThanhTien DECIMAL(18,2) NOT NULL,
    CONSTRAINT FK_CTHD_HD FOREIGN KEY (MaHD) REFERENCES HOA_DON(MaHD),
    CONSTRAINT FK_CTHD_KC FOREIGN KEY (MaSPKC) REFERENCES SAN_PHAM_KICH_CO(MaSPKC),
    CONSTRAINT UQ_CTHD_HD_KC UNIQUE (MaHD, MaSPKC),
    CONSTRAINT CK_CTHD_SoLuong CHECK (SoLuong > 0),
    CONSTRAINT CK_CTHD_DonGia CHECK (DonGia >= 0),
    CONSTRAINT CK_CTHD_ThanhTien CHECK (ThanhTien = SoLuong * DonGia)
);
